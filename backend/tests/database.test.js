const test = require("node:test");
const assert = require("node:assert/strict");
const { preparePostgresQuery } = require("../src/config/database");

test("converts MySQL placeholders and SQL functions for PostgreSQL", () => {
  const query = preparePostgresQuery(
    "SELECT DATABASE() AS databaseName WHERE title LIKE ? AND id = ?"
  );

  assert.equal(
    query,
    'SELECT current_database() AS "databaseName" WHERE title ILIKE $1 AND id = $2'
  );
});

test("does not convert question marks inside strings or comments", () => {
  const query = preparePostgresQuery(
    "SELECT '?' AS marker WHERE title = ? -- ?\n/* ? */ AND details = 'text?'"
  );

  assert.equal(
    query,
    "SELECT '?' AS marker WHERE title = $1 -- ?\n/* ? */ AND details = 'text?'"
  );
});

test("preserves PostgreSQL identity syntax in schema statements", () => {
  const statement =
    "CREATE TABLE example (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)";

  assert.equal(preparePostgresQuery(statement), statement);
});
