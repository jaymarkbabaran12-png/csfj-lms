require("dotenv").config();

const pool = require("../src/config/database");

async function migrate() {
  const db = await pool.getConnection();

  try {
    if (pool.isPostgres) {
      await db.execute(`
        CREATE TABLE IF NOT EXISTS hub_quiz_deadlines (
          quiz_id INTEGER NOT NULL PRIMARY KEY,
          due_date TIMESTAMP NOT NULL
        )
      `);
      await db.execute(`
        CREATE TABLE IF NOT EXISTS hub_quiz_submissions (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          quiz_id INTEGER NOT NULL,
          student_id INTEGER NOT NULL,
          score NUMERIC(10, 2) NOT NULL DEFAULT 0,
          submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
          CONSTRAINT uq_hub_quiz_student UNIQUE (quiz_id, student_id)
        )
      `);
      await db.execute(`
        CREATE INDEX IF NOT EXISTS ix_hub_quiz_submissions_student
        ON hub_quiz_submissions(student_id)
      `);
      await db.execute(`
        CREATE TABLE IF NOT EXISTS hub_quiz_submission_answers (
          submission_id BIGINT NOT NULL,
          question_id INTEGER NOT NULL,
          choice_id INTEGER NOT NULL,
          PRIMARY KEY (submission_id, question_id)
        )
      `);
      await db.execute(`
        CREATE INDEX IF NOT EXISTS ix_hub_quiz_answers_question
        ON hub_quiz_submission_answers(question_id)
      `);
    } else {
      await db.execute(`
        CREATE TABLE IF NOT EXISTS hub_quiz_deadlines (
          quiz_id INT NOT NULL PRIMARY KEY,
          due_date DATETIME NOT NULL
        ) ENGINE=InnoDB
      `);
      await db.execute(`
        CREATE TABLE IF NOT EXISTS hub_quiz_submissions (
          id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
          quiz_id INT NOT NULL,
          student_id INT NOT NULL,
          score DECIMAL(10, 2) NOT NULL DEFAULT 0,
          submitted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
          UNIQUE KEY uq_hub_quiz_student (quiz_id, student_id),
          KEY ix_hub_quiz_submissions_student (student_id)
        ) ENGINE=InnoDB
      `);
      await db.execute(`
        CREATE TABLE IF NOT EXISTS hub_quiz_submission_answers (
          submission_id BIGINT NOT NULL,
          question_id INT NOT NULL,
          choice_id INT NOT NULL,
          PRIMARY KEY (submission_id, question_id),
          KEY ix_hub_quiz_answers_question (question_id)
        ) ENGINE=InnoDB
      `);
    }

    console.log("Hub integration tables are ready.");
  } finally {
    db.release();
    await pool.end();
  }
}

migrate().catch((error) => {
  console.error("Hub integration migration failed:", error.message);
  process.exitCode = 1;
});